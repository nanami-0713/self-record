// 数据口径 = lifttime foods.js FOODS（2026-10-06 无损转译，326 项 ≥ 320 要求）：
// 每 100g 的 kcal/蛋白/碳水/脂肪 + 常用份单位与单份克数 + tags 十档标签。
// 数值为《中国食物成分表》/USDA 公开数据的常用近似值，供日常记录参考，不作医学用途。
// 转译方式：脚本读取 reference/lifttime/js/foods.js 逐字段生成（无手抄），锚点用例见
// DietNutritionTests（宫保鸡丁 k=130、红烧肉 k=400、鸡腿 p=16、火龙果 fruit、
// 手抓饼 u=个、电解质水 k=25、白酒 两/50g、鸡胸肉丸 袋/100g 等）。

/// 食物库条目（内置库与自学习库的统一形状，= lifttime foods.js 的 {n,a,u,g,k,p,c,f,t}）。
/// `Per100g` 的 `portionGrams`/`portionUnit` 承载原 g/u 字段（「碗=200g」这类常用份）。
public struct FoodLibraryEntry: Codable, Sendable, Equatable, Identifiable {
    public var id: String { name }
    public var name: String
    public var aliases: [String]
    public var per100g: Per100g
    public var tags: [FoodTag]

    public init(name: String,
                aliases: [String] = [],
                per100g: Per100g,
                tags: [FoodTag] = []) {
        self.name = name
        self.aliases = aliases
        self.per100g = per100g
        self.tags = tags
    }
}

